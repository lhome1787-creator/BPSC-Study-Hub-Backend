let currentQuestion = 0;
let score = 0;
let answered = false;

function loadQuestion() {
    const q = questions[currentQuestion];
    const progress = ((currentQuestion + 1) / questions.length) * 100;

document.getElementById("progressBar").style.width =
    progress + "%";

    

    document.getElementById("questionNumber").innerHTML =
        "प्रश्न " + (currentQuestion + 1) + " / " + questions.length;

    document.getElementById("question").innerHTML =
        q.question;

    const optionsDiv = document.getElementById("options");

    optionsDiv.innerHTML = "";

    answered = false;

    q.options.forEach(function(option) {

        const button = document.createElement("button");

        button.innerHTML = option;

        button.onclick = function() {
    checkQuizAnswer(option, button);

    const allButtons = document.querySelectorAll("#options button");

    allButtons.forEach(function(btn) {
        btn.disabled = true;
    });
};
     

        optionsDiv.appendChild(button);
        optionsDiv.appendChild(document.createElement("br"));
        optionsDiv.appendChild(document.createElement("br"));

    });

    document.getElementById("result").innerHTML = "";
}


function checkQuizAnswer(selectedAnswer, button) {

    if (answered) {
        return;
    }

    answered = true;

    const correctAnswer = questions[currentQuestion].answer;

    if (selectedAnswer === correctAnswer) {

        score++;
        button.style.background = "green";
button.style.color = "white";

        document.getElementById("result").innerHTML =
            "✅ सही उत्तर! 🎉";

    } else {
        button.style.background = "red";
button.style.color = "white";

        document.getElementById("result").innerHTML =
            "❌ गलत! सही उत्तर: " + correctAnswer;

    }
}


function nextQuestion() {

    if (!answered) {

        document.getElementById("result").innerHTML =
            "⚠️ पहले एक option चुनें।";

        return;
    }

    currentQuestion++;

    if (currentQuestion < questions.length) {

        loadQuestion();

    } else {

        document.getElementById("questionNumber").innerHTML =
            "🎉 Quiz समाप्त";

        const percentage = (score / questions.length) * 100;

document.getElementById("question").innerHTML =
    "🎉 आपका Final Score: " + score + " / " + questions.length +
    "<br>📊 प्रतिशत: " + percentage.toFixed(0) + "%";
        document.getElementById("options").innerHTML = "";
        const restartButton = document.createElement("button");
restartButton.innerHTML = "🔄 Restart Quiz";

restartButton.onclick = function() {
    currentQuestion = 0;
    score = 0;
    answered = false;

    restartButton.remove();
    loadQuestion();
};

document.getElementById("options").appendChild(restartButton);

        document.getElementById("result").innerHTML =
            "बहुत बढ़िया! अपनी तैयारी जारी रखें। 💪";
    }
}


